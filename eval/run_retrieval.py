"""Retrieval eval: does each search mode find the page that holds the answer?

No LLM and no API key needed, so it runs in CI on every pull request.

    python eval/run_retrieval.py            # print + write EVAL.md and eval/results.json
    python eval/run_retrieval.py --check    # also fail (exit 1) if scores drop below eval/baseline.json

Metrics, over the answerable questions in eval/golden.jsonl:
  hit@1      share of questions whose top result is on an expected page
  recall@5   share whose expected page appears anywhere in the top 5
  MRR@10     mean of 1/rank of the first correct result (0 if not in top 10)
For the out-of-scope questions it reports the best reranker score, to set MIN_RERANK_SCORE.
"""

import argparse
import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from belanjawan.generate import MIN_RERANK_SCORE  # noqa: E402
from belanjawan.index import load_index  # noqa: E402
from belanjawan.retrieve import MODES, search  # noqa: E402

GOLDEN = ROOT / "eval" / "golden.jsonl"
BASELINE = ROOT / "eval" / "baseline.json"
TOLERANCE = 0.03  # allowed drop before CI fails (one question out of 34 is ~0.03)


def load_golden() -> list[dict]:
    return [json.loads(line) for line in GOLDEN.read_text(encoding="utf-8").splitlines() if line.strip()]


def first_correct_rank(hits, item) -> int | None:
    """1-based rank of the first hit on an expected (doc, page), or None."""
    for rank, hit in enumerate(hits, start=1):
        if hit.chunk.doc == item["doc"] and hit.chunk.page in item["pages"]:
            return rank
    return None


def evaluate(index, golden) -> dict:
    answerable = [g for g in golden if g["doc"]]
    out_of_scope = [g for g in golden if not g["doc"]]
    results = {"n_questions": len(answerable), "modes": {}, "misses": {}}
    for mode in MODES:
        started = time.perf_counter()
        ranks = [first_correct_rank(search(index, g["question"], mode, k=10), g) for g in answerable]
        elapsed = time.perf_counter() - started
        results["modes"][mode] = {
            "hit@1": round(sum(r == 1 for r in ranks) / len(ranks), 3),
            "recall@5": round(sum(r is not None and r <= 5 for r in ranks) / len(ranks), 3),
            "MRR@10": round(sum(1 / r for r in ranks if r) / len(ranks), 3),
            "ms_per_query": round(1000 * elapsed / len(ranks), 1),
        }
        results["misses"][mode] = [g["id"] for g, r in zip(answerable, ranks) if r is None or r > 5]

    def best_rerank(q):
        hits = search(index, q, "hybrid_rerank", k=1)
        return hits[0].score if hits else 0.0

    in_scores = [best_rerank(g["question"]) for g in answerable]
    out_scores = [best_rerank(g["question"]) for g in out_of_scope]
    results["refusal"] = {
        "threshold": MIN_RERANK_SCORE,
        "in_scope_best_score_min": round(min(in_scores), 4),
        "in_scope_best_score_median": round(statistics.median(in_scores), 4),
        "out_of_scope_best_score_max": round(max(out_scores), 4) if out_scores else None,
        "in_scope_wrongly_refused": sum(s < MIN_RERANK_SCORE for s in in_scores),
        "out_of_scope_let_through": sum(s >= MIN_RERANK_SCORE for s in out_scores),
        "n_out_of_scope": len(out_scores),
    }
    return results


def to_markdown(r: dict) -> str:
    lines = [
        "# Retrieval eval",
        "",
        f"Golden set: {r['n_questions']} answerable questions + {r['refusal']['n_out_of_scope']} "
        "out-of-scope ones (`eval/golden.jsonl`). A result counts as correct only if it comes from "
        "the expected document **and** page. Generated by `python eval/run_retrieval.py`.",
        "",
        "| Mode | hit@1 | recall@5 | MRR@10 | ms/query | missed (not in top 5) |",
        "|---|---|---|---|---|---|",
    ]
    for mode, m in r["modes"].items():
        misses = ", ".join(r["misses"][mode]) or "none"
        lines.append(f"| `{mode}` | {m['hit@1']:.3f} | {m['recall@5']:.3f} | {m['MRR@10']:.3f} | "
                     f"{m['ms_per_query']} | {misses} |")
    f = r["refusal"]
    lines += [
        "",
        "## Refusal threshold (hybrid_rerank)",
        "",
        f"`MIN_RERANK_SCORE = {f['threshold']}`: the API refuses without calling the LLM when the best "
        "reranker score is below this.",
        "",
        f"- Answerable questions: lowest best score {f['in_scope_best_score_min']}, median "
        f"{f['in_scope_best_score_median']}; wrongly refused: {f['in_scope_wrongly_refused']}",
        f"- Out-of-scope questions: highest best score {f['out_of_scope_best_score_max']}; let through to "
        f"the LLM: {f['out_of_scope_let_through']} of {f['n_out_of_scope']} (the prompt's OUT_OF_SCOPE "
        "rule and the citation check are the second line of defence)",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if below eval/baseline.json")
    args = parser.parse_args()

    results = evaluate(load_index(ROOT / "index"), load_golden())
    (ROOT / "eval" / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    report = to_markdown(results)
    (ROOT / "EVAL.md").write_text(report, encoding="utf-8")
    print(report)

    if args.check:
        baseline = json.loads(BASELINE.read_text(encoding="utf-8"))
        failures = [
            f"{mode} {metric}: {results['modes'][mode][metric]} < baseline {floor} - {TOLERANCE}"
            for mode, metrics in baseline.items()
            for metric, floor in metrics.items()
            if results["modes"][mode][metric] < floor - TOLERANCE
        ]
        if failures:
            print("REGRESSION:\n  " + "\n  ".join(failures))
            sys.exit(1)
        print("No regression against eval/baseline.json")


if __name__ == "__main__":
    main()
